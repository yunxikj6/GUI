}

download_signed_claude() (
    local dir=$1 arch=$2 uri=$3 fingerprint=$4 key=$5
    [[ $(primary_keys "$key") == "$fingerprint" ]] || { echo 'Claude 官方仓库公钥指纹不匹配。' >&2; exit 74; }
    mkdir -p "$dir"/{lists/partial,empty,downloads}
    cat >"$dir/vendor.sources" <<EOF
Types: deb
URIs: $uri
Suites: stable
Components: main
Architectures: $arch
Signed-By: $key $fingerprint
EOF
    # APT reads this file before loading configuration fragments. The private
    # update has no system sources, hooks, package cache or installed candidates.
    cat >"$dir/apt.conf" <<EOF
Dir::Etc::main "/dev/null";
Dir::Etc::parts "$dir/empty";
Dir::Etc::preferences "/dev/null";
Dir::Etc::preferencesparts "$dir/empty";
Dir::Etc::sourcelist "$dir/vendor.sources";
Dir::Etc::sourceparts "$dir/empty";
Dir::State::lists "$dir/lists";
Dir::State::status "/dev/null";
Dir::Cache::pkgcache "";
Dir::Cache::srcpkgcache "";
Acquire::Languages "none";
Acquire::https::Verify-Peer "true";
Acquire::https::Verify-Host "true";
EOF
    export APT_CONFIG="$dir/apt.conf"
    apt-get -o APT::Update::Error-Mode=any update
    cd "$dir/downloads"
    apt-get download "claude-desktop:$arch"
    local files=(claude-desktop_*_"$arch".deb)
    [[ ${#files[@]} == 1 && -f ${files[0]} ]] || { echo '官方仓库没有提供唯一匹配的软件包。' >&2; exit 74; }
    mv -- "${files[0]}" "$dir/claude-desktop.deb"
)

verify_package() {
    local path=$1 name=$2 arch=$3
    if [[ $(dpkg-deb -f "$path" Package) != "$name" || $(dpkg-deb -f "$path" Architecture) != "$arch" ]]; then
        printf '下载的软件包身份或架构不符。需要 %s (%s)。\n' "$name" "$arch" >&2
        return 74
    fi
}

installed_at_least() {
    local package=$1 arch=$2 version=$3 status
    status=$(dpkg-query -W -f='${Status} ${Architecture} ${Version}' -- "$package:$arch" 2>/dev/null) || return 1
    [[ $status == "install ok installed $arch "* ]] && dpkg --compare-versions "${status##* }" ge "$version"
}

install_debs() (
    local file name digest rules='' hook stage
    local staged=()
    stage=$(mktemp -d /tmp/cloud-workspace-packages.XXXXXXXX)
    trap 'rm -rf -- "$stage"' EXIT
    for file; do
        name=$(dpkg-deb -f "$file" Package)
        digest=$(sha256sum <"$file")
        digest=${digest%% *}
        [[ $digest =~ ^[a-f0-9]{64}$ && ( $name == chatgpt || $name == claude-desktop ) ]] || return 74
        rules+=" $name) expected=$digest ;;"
        ln -- "$file" "$stage/$name.deb"
        chmod 0644 "$stage/$name.deb"
        staged+=("$stage/$name.deb")
    done
    # APT can prefer an indexed package with the same name and version over an
    # explicit local .deb. Check the bytes actually passed to dpkg under its lock.
    hook='set -eu; while IFS= read -r f; do
        n=$(/usr/bin/dpkg-deb -f "$f" Package)
        case "$n" in '"$rules"' *) continue ;; esac
        h=$(/usr/bin/sha256sum <"$f")
        if [ "${h%% *}" != "$expected" ]; then
            echo "APT 选择的 $n 与已验证的厂商文件不同。已中止安装。" >&2; exit 1
        fi
    done'
    # APT's _apt user needs to traverse this directory and read only the public .deb files.
    # Keep the private signing configuration and temporary indices inside the original 0700 tree.
    chmod 0711 "$stage"
    sudo -- /usr/bin/apt-get -o APT::Get::Assume-Yes=false --no-remove \
        -o "DPkg::Pre-Install-Pkgs::=$hook" install "${staged[@]}"
)

setup_vendor_apps() {
    local choice='' answer='' arch name
    if [[ $# == 2 && $1 == --app ]]; then shift; fi
    case "$#:${1:-}" in
        1:--help|1:-h) echo '用法：setup-vendor-apps.sh [--app chatgpt|claude|both|none]'; return ;;
        1:none) echo '已跳过安装。'; return ;;
        0:) ;;
        1:chatgpt|1:claude|1:both) choice=$1 ;;
        *) echo '用法：setup-vendor-apps.sh [--app chatgpt|claude|both|none]' >&2; return 64 ;;
    esac
    if [[ ! -t 0 || ! -t 1 ]]; then echo '请在 Ubuntu 交互终端中运行安装程序。' >&2; return 70; fi
    arch=$(platform_arch)
    if [[ -z $choice ]]; then
        printf '安装 Ubuntu 官方桌面应用\n  1  ChatGPT\n  2  Claude\n  3  两者\n  0  取消\n'
        read -r -p '请选择 [0] ' answer || return 130
        case $answer in
            1|chatgpt) choice=chatgpt ;; 2|claude) choice=claude ;; 3|both) choice=both ;;
            ''|0|none) echo '已取消。'; return 130 ;;
            *) echo '未识别选项。'; return 64 ;;
        esac
    fi
    case "$choice" in
        chatgpt) name='ChatGPT' ;;
        claude) name='Claude' ;;
        both) name='ChatGPT 和 Claude' ;;
    esac
    printf '将在本机 Ubuntu 中安装 %s。安装程序将下载官方软件包，并使用 sudo 和 APT 安装。厂商软件包可注册系统更新源、签名密钥和自动更新配置。\n' "$name"
    if ! read -r -p '开始下载并安装？输入 y 继续，按 Enter 取消 [y/N] ' answer || [[ ! $answer =~ ^([yY]|[yY][eE][sS])$ ]]; then
        echo '已取消。'; return 130
    fi
    if ! command -v curl >/dev/null; then
        echo '未找到 curl，无法下载官方软件包。请先安装 Ubuntu 的 curl 软件包。' >&2
        return 69
    fi
    if [[ $choice != chatgpt ]] && ! command -v gpg >/dev/null; then
        echo '未找到 gpg，无法核对 Claude 官方签名密钥。请先安装 Ubuntu 的 gpg 软件包。' >&2
        return 69
    fi
    work=$(mktemp -d /tmp/cloud-workspace-vendors.XXXXXXXX)
    trap 'rm -rf -- "$work"' EXIT
    mkdir -m 700 "$work/gnupg"
    local debs=()
    if [[ $choice != claude ]]; then
        fetch_https "https://persistent.oaistatic.com/codex-app-prod/linux/deb/latest/chatgpt_${arch}.deb" "$work/chatgpt.deb"
        verify_package "$work/chatgpt.deb" chatgpt "$arch"
        debs+=("$work/chatgpt.deb")
    fi
    if [[ $choice != chatgpt ]]; then
        fetch_https 'https://downloads.claude.ai/claude-desktop/key.asc' "$work/claude.asc"
        download_signed_claude "$work" "$arch" https://downloads.claude.ai/claude-desktop/apt/stable "$claude_key" "$work/claude.asc"
        verify_package "$work/claude-desktop.deb" claude-desktop "$arch"
        debs+=("$work/claude-desktop.deb")
    fi
    local file package version
    local pending=()
    for file in "${debs[@]}"; do
        package=$(dpkg-deb -f "$file" Package)
        version=$(dpkg-deb -f "$file" Version)
        if installed_at_least "$package" "$arch" "$version"; then
            printf '%s 已安装当前或更高版本。\n' "$package"
        else
            check_vendor_files "$package" "$arch"
            pending+=("$file")
        fi
    done
    if (( ${#pending[@]} )); then
        command -v sudo >/dev/null || { echo '未找到 sudo。请从具有 sudo 权限的 Ubuntu 用户运行。' >&2; return 69; }
        install_debs "${pending[@]}"
    fi
    for file in "${debs[@]}"; do
        package=$(dpkg-deb -f "$file" Package)
        version=$(dpkg-deb -f "$file" Version)
        if ! installed_at_least "$package" "$arch" "$version"; then
            printf 'APT 已退出，dpkg 尚未确认 %s (%s %s) 安装完成。请检查上面的 APT 输出。\n' "$package" "$arch" "$version" >&2
            return 75
        fi
    done
    echo '安装完成。可从 Ubuntu 应用菜单打开所选应用。'
}

if [[ ${BASH_SOURCE[0]} == "$0" ]]; then
    trap 'exit 130' INT
    setup_vendor_apps "$@"
fi
