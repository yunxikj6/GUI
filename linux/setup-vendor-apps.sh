#!/usr/bin/env bash
# Explicit, interactive installation of the official Ubuntu desktop applications.
set -euo pipefail

claude_key=31DDDE24DDFAB679F42D7BD2BAA929FF1A7ECACE

platform_arch() {
    local ID='' VERSION_ID='' arch
    . /etc/os-release
    arch=$(dpkg --print-architecture)
    if [[ $ID != ubuntu || $VERSION_ID != 24.04 || ( $arch != amd64 && $arch != arm64 ) ]]; then
        echo '此安装入口支持 Ubuntu 24.04 LTS 的 amd64 和 arm64。' >&2
        return 65
    fi
    printf '%s\n' "$arch"
}

fetch_https() {
    curl --disable --proto '=https' --proto-redir '=https' --tlsv1.2 --location --fail \
        --show-error --progress-bar --connect-timeout 30 --output "$2" -- "$1"
}

primary_keys() {
    gpg --batch --no-options --homedir "$work/gnupg" --with-colons --show-keys -- "$1" |
        awk -F: '$1=="pub" { primary=1 } primary && $1=="fpr" { print $10; primary=0 }'
}

check_managed_file() {
    local path=$1 digest
    shift
    [[ -e $path || -L $path ]] || return 0
    if [[ -f $path && ! -L $path && -r $path ]]; then
        digest=$(sha256sum <"$path")
        local allowed
        for allowed; do [[ ${digest%% *} != "$allowed" ]] || return 0; done
    fi
    printf '检测到已有自定义文件或链接。请检查 %s 后决定是否使用厂商原生安装步骤。\n' "$path" >&2
    return 73
}

