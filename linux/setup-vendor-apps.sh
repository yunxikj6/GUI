    if [[ $1 == chatgpt ]]; then
        local sources_hash=9ff8ae7b9e2e73b9fa1a31383c4cde964e159bab39aee762aef4918d1a4f2cfd
        if [[ $2 == arm64 ]]; then sources_hash=34b4f31ce106937a5858560b7c49503fedccedc067d41b0e282d2dafffae2a4d; fi
        check_managed_file /usr/share/keyrings/chatgpt-archive-keyring.gpg 23e2cfbdef6afe95505f9e95a2cb63585da7ffe9b06a51ec08a32407c847d596
        check_managed_file /etc/apt/sources.list.d/chatgpt.sources "$sources_hash"
        check_managed_file /var/lib/chatgpt/repository.sources "$sources_hash"
        check_managed_file /etc/default/chatgpt fb6ebc7d7c84dd4bac8805764080244ec8abef185f393f01592731030a76e9bf d7ec575e494acb1c894a2c3b42e46be332982aba839b0f7be281d936e75fbbb3
    else
        check_managed_file /usr/share/keyrings/claude-desktop-archive-keyring.asc bd70a5e4a268002704024ceba7f8446024114e94f3f0bdd11c23a9e592be81c6
        # Anthropic documents a manual one-line source; its installer also generates a marked equivalent.
